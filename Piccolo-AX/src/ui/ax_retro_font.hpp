class RetroBitmapFont {
public:
    RetroBitmapFont() noexcept {
        glyphs_.fill({0, 0, 0, 0, 0});
        for (std::size_t i = 0; i < kBuiltinFontData.size(); ++i) {
            glyphs_[i] = kBuiltinFontData[i];
        }
    }

    bool LoadOverrideFile(const std::string& path) {
        std::ifstream file(path);
        if (!file.is_open()) {
            return false;
        }
        std::string line;
        std::size_t glyph_idx = 0;
        while (glyph_idx < 141 && std::getline(file, line)) {
            if (line == "EOF") {
                break;
            }
            if (line.empty() || line[0] == ';') {
                continue;
            }
            glyphs_[glyph_idx][0] = ParseBitRow(line);
            for (int row = 1; row < kGlyphHeight; ++row) {
                if (!std::getline(file, line)) {
                    return false;
                }
                glyphs_[glyph_idx][static_cast<std::size_t>(row)] = ParseBitRow(line);
            }
            ++glyph_idx;
        }
        return true;
    }

    [[nodiscard]] std::size_t MapAsciiToGlyph(char ch) const noexcept {
        const unsigned char u = static_cast<unsigned char>(std::toupper(static_cast<unsigned char>(ch)));
        if (u >= '0' && u <= '9') return static_cast<std::size_t>(u - '0' + 0x01);
        if (u >= 'A' && u <= 'Z') return static_cast<std::size_t>(u - 'A' + 0x0B);
        switch (u) {
            case '-': return 0x25;
            case '_': return 0x26;
            case '~': return 0x27;
            case '.': return 0x28;
            case '/': return 0x29;
            case '<': return 0x2A;
            case '>': return 0x2B;
            case '[': return 0x2C;
            case ']': return 0x2D;
            case ':': return 0x2E;
            case '&': return 0x2F;
            case '#': return 0x31;
            case '=': return 0x32;
            case '"': return 0x33;
            case '\\': return 0x34;
            case '*': return 0x35;
            case '?': return 0x36;
            case '%': return 0x37;
            case '+': return 0x38;
            case ',': return 0x39;
            case '(': return 0x3A;
            case ')': return 0x3B;
            case '@': return 0x3C;
            case '\'': return 0x3D;
            case '!': return 0x3E;
            case '$': return 0x3F;
            case ';': return 0x40;
            case '`': return 0x41;
            case '^': return 0x42;
            case '{': return 0x43;
            case '}': return 0x44;
            default: return 0x00;
        }
    }

    [[nodiscard]] const std::array<std::uint8_t, kGlyphHeight>& Glyph(std::size_t idx) const noexcept {
        return glyphs_[idx < glyphs_.size() ? idx : 0];
    }

private:
    static std::uint8_t ParseBitRow(std::string_view bits) noexcept {
        std::uint8_t out = 0;
        const std::size_t limit = bits.size() < 8 ? bits.size() : 8;
        for (std::size_t x = 0; x < limit; ++x) {
            if (bits[x] == '1') {
                out |= static_cast<std::uint8_t>(1U << (7U - x));
            }
        }
        return out;
    }

    std::array<std::array<std::uint8_t, kGlyphHeight>, kGlyphCount> glyphs_{};
};

